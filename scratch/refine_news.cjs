// 执行替换
function replaceBlock(content, startMarker, endMarker, replacement) {
  const startIdx = content.indexOf(startMarker);
  if (startIdx === -1) throw new Error('Start marker not found: ' + startMarker.slice(0, 30));
  const endIdx = content.indexOf(endMarker, startIdx);
  if (endIdx === -1) throw new Error('End marker not found: ' + endMarker.slice(0, 30));
  return content.slice(0, startIdx) + replacement + content.slice(endIdx + endMarker.length);
}

